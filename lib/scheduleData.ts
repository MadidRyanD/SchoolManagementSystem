// Build subjects, subject-teachers, and schedule items deterministically
const subjectMap = new Map<string, SubjectItem>();
const subjectTeacherMap = new Map<string, SubjectTeacherItem>();
const builtSchedules: ClassScheduleItem[] = [];

let nextSubjectId = 1;
let nextSTId = 1;
let nextScheduleId = 1;

for (const [classCode, day, startTime, endTime, subjectAr, teacherAr, room] of RAW_SLOTS) {
  const classId = CLASS_CODE_TO_ID[classCode];
  const teacherId = TEACHER_NAME_TO_ID[teacherAr];

  if (!classId || !teacherId) {
    throw new Error(`Invalid classCode (${classCode}) or teacher (${teacherAr})`);
  }

  const subKey = `${classId}::${subjectAr}`;
  let subject = subjectMap.get(subKey);
  if (!subject) {
    const id = nextSubjectId++;
    subject = {
      SubjectID: id,
      ClassID: classId,
      SubjectClass: subjectAr,
      SubjectCode: `SUB-${String(id).padStart(3, '0')}`,
      SubjectArabic: subjectAr,
      Semester: '1st',
    };
    subjectMap.set(subKey, subject);
  }

  const stKey = `${classId}::${subject.SubjectID}::${teacherId}`;
  if (!subjectTeacherMap.has(stKey)) {
    subjectTeacherMap.set(stKey, {
      ID: nextSTId++,
      ClassID: classId,
      SubjectID: subject.SubjectID,
      TeacherID: teacherId,
    });
  }

  builtSchedules.push({
    ID: nextScheduleId++,
    ClassID: classId,
    SubjectID: subject.SubjectID,
    TeacherID: teacherId,
    Day: day,
    StartTime: startTime,
    EndTime: endTime,
    Room: room,
  });
}

export const scheduleSubjects: SubjectItem[] = Array.from(subjectMap.values());
export const scheduleSubjectTeachers: SubjectTeacherItem[] = Array.from(subjectTeacherMap.values());
export const scheduleItems: ClassScheduleItem[] = builtSchedules;

function format12Hour(hhmm: string): string {
  const [hStr, mStr] = hhmm.split(':');
  let h = parseInt(hStr, 10);
  if (h > 12) h -= 12;
  return `${h}:${mStr}`;
}

/**
 * Builds sorted, deduplicated time-slot rows for any list of schedule items,
 * automatically inserting the 9:15 - 9:30 recess break when morning slots exist.
 */
export function buildScheduleTimeSlots(schedules: ClassScheduleItem[]): ScheduleTimeSlot[] {
  const defaultSlots: ScheduleTimeSlot[] = [
    { label: '7:15 - 7:55', start: '07:15', end: '07:55', isBreak: false },
    { label: '7:55 - 8:35', start: '07:55', end: '08:35', isBreak: false },
    { label: '8:35 - 9:15', start: '08:35', end: '09:15', isBreak: false },
    { label: '9:15 - 9:30', start: '09:15', end: '09:30', isBreak: true, titleArabic: 'فسحة / استراحة' },
    { label: '9:30 - 10:10', start: '09:30', end: '10:10', isBreak: false },
    { label: '10:10 - 10:50', start: '10:10', end: '10:50', isBreak: false },
    { label: '10:50 - 11:30', start: '10:50', end: '11:30', isBreak: false },
    { label: '1:00 - 1:40', start: '13:00', end: '13:40', isBreak: false },
    { label: '1:40 - 2:20', start: '13:40', end: '14:20', isBreak: false },
    { label: '2:20 - 3:00', start: '14:20', end: '15:00', isBreak: false },
    { label: '3:00 - 3:40', start: '15:00', end: '15:40', isBreak: false },
    { label: '3:40 - 4:20', start: '15:40', end: '16:20', isBreak: false },
  ];

  if (schedules.length === 0) return defaultSlots;

  const uniqueMap = new Map<string, { start: string; end: string }>();
  for (const s of schedules) {
    const key = `${s.StartTime}-${s.EndTime}`;
    if (!uniqueMap.has(key)) {
      uniqueMap.set(key, { start: s.StartTime, end: s.EndTime });
    }
  }

  const sorted = Array.from(uniqueMap.values()).sort((a, b) =>
    a.start.localeCompare(b.start) || a.end.localeCompare(b.end)
  );

  const slots: ScheduleTimeSlot[] = [];
  let breakInserted = false;

  for (const item of sorted) {
    if (!breakInserted && item.start >= '09:30' && slots.some(s => s.start === '08:35')) {
      slots.push({
        label: '9:15 - 9:30',
        start: '09:15',
        end: '09:30',
        isBreak: true,
        titleArabic: 'فسحة / استراحة',
      });
      breakInserted = true;
    }
    slots.push({
      label: `${format12Hour(item.start)} - ${format12Hour(item.end)}`,
      start: item.start,
      end: item.end,
      isBreak: false,
    });
  }

  return slots;
}
